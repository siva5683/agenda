import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';
import { GoogleGenAI } from '@google/genai';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = parseInt(process.env.PORT || '3000', 10);

app.use(express.json({ limit: '10mb' }));
app.use(express.urlencoded({ extended: true, limit: '10mb' }));

// Shared Gemini Client
const ai = new GoogleGenAI({
  apiKey: process.env.GEMINI_API_KEY || '',
  httpOptions: {
    headers: {
      'User-Agent': 'aistudio-build',
    },
  },
});

// Supported Aspect Ratios & Sizes as required by prompt
// "aspect ratio (1:1, 2:3, 3:2, 3:4, 4:3, 9:16, 16:9, and 21:9)"
// "image size (1K, 2K, and 4K)"
const VALID_ASPECT_RATIOS = ['1:1', '2:3', '3:2', '3:4', '4:3', '9:16', '16:9', '21:9'];
const VALID_SIZES = ['1K', '2K', '4K'];

// API: Generate Dish Image using Gemini Image Models
app.post('/api/generate-dish-image', async (req, res) => {
  try {
    const {
      prompt,
      model = 'gemini-3-pro-image-preview',
      aspectRatio = '1:1',
      imageSize = '1K',
    } = req.body;

    if (!prompt || typeof prompt !== 'string') {
      return res.status(400).json({ error: 'Prompt is required' });
    }

    if (!process.env.GEMINI_API_KEY) {
      return res.status(500).json({
        error: 'GEMINI_API_KEY is not configured in server environment.',
      });
    }

    // Determine target model name (support gemini-3-pro-image-preview or gemini-3.1-flash-image-preview)
    let selectedModel = model;
    if (selectedModel !== 'gemini-3-pro-image-preview' && selectedModel !== 'gemini-3.1-flash-image-preview') {
      selectedModel = 'gemini-3-pro-image-preview';
    }

    const safeAspectRatio = VALID_ASPECT_RATIOS.includes(aspectRatio) ? aspectRatio : '1:1';
    const safeImageSize = VALID_SIZES.includes(imageSize) ? imageSize : '1K';

    const enhancedPrompt = `A professional, mouthwatering food photography shot of ${prompt}. Masterfully plated, warm vibrant restaurant lighting, appetizing steam, fresh herbs, shallow depth of field, 8k culinary perfection.`;

    const response = await ai.models.generateContent({
      model: selectedModel,
      contents: {
        parts: [
          {
            text: enhancedPrompt,
          },
        ],
      },
      config: {
        imageConfig: {
          aspectRatio: safeAspectRatio as any,
          imageSize: safeImageSize as any,
        },
      },
    });

    let imageUrl = '';
    const parts = response.candidates?.[0]?.content?.parts || [];
    for (const part of parts) {
      if (part.inlineData?.data) {
        const mimeType = part.inlineData.mimeType || 'image/png';
        imageUrl = `data:${mimeType};base64,${part.inlineData.data}`;
        break;
      }
    }

    if (!imageUrl) {
      return res.status(502).json({
        error: 'No image data was generated by the model. Please adjust the prompt and try again.',
      });
    }

    return res.json({
      success: true,
      imageUrl,
      model: selectedModel,
      aspectRatio: safeAspectRatio,
      imageSize: safeImageSize,
      prompt,
    });
  } catch (error: any) {
    console.error('Error generating image with Gemini:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to generate dish image.',
    });
  }
});

// API: AI Chef Dish Idea Assistant (creates complete recipe, dish specs, price in INR, and image prompt)
app.post('/api/ai-chef-suggest', async (req, res) => {
  try {
    const { idea = 'fusion Indian dish' } = req.body;

    if (!process.env.GEMINI_API_KEY) {
      // Fallback response if key is missing
      return res.json({
        name: 'Tandoori Truffle Paneer Steak',
        description: 'Smoked paneer slab infused with black truffle glaze, charred tandoori spices and micro-coriander.',
        category: 'Indian',
        price: 289,
        isVeg: true,
        ingredients: ['Paneer', 'Black Truffle Oil', 'Kashmiri Red Chilli', 'Greek Yogurt', 'Bell Peppers', 'Garam Masala'],
        imagePrompt: 'A gourmet dish of charred Tandoori Truffle Paneer Steak with roasted bell peppers, fresh mint chutney swirl on a black slate plate',
      });
    }

    const response = await ai.models.generateContent({
      model: 'gemini-3.8-flash',
      contents: `Create an innovative, delectable restaurant menu dish inspired by: "${idea}". 
      Respond strictly with a JSON object in this exact format:
      {
        "name": "Dish Name",
        "description": "Appetizing 1-2 sentence description",
        "category": "One of: Pizza, Burgers, Indian, Chinese, Desserts, Drinks, Snacks",
        "price": <Price in INR as integer between 99 and 499>,
        "isVeg": <true or false>,
        "ingredients": ["ingredient 1", "ingredient 2", "ingredient 3", "ingredient 4", "ingredient 5"],
        "imagePrompt": "Detailed visual description of this dish for food photography"
      }`,
      config: {
        responseMimeType: 'application/json',
      },
    });

    const parsed = JSON.parse(response.text || '{}');
    return res.json(parsed);
  } catch (err: any) {
    console.error('AI Chef Suggest error:', err);
    return res.json({
      name: 'Smoky Malai Chicken Roulade',
      description: 'Tender chicken breast stuffed with spiced cream cheese, pistachios and tandoori glaze.',
      category: 'Indian',
      price: 279,
      isVeg: false,
      ingredients: ['Chicken Breast', 'Cream Cheese', 'Pistachios', 'Cardamom', 'Cream Gravy'],
      imagePrompt: 'Smoky Malai Chicken Roulade sliced on a dark ceramic platter with saffron cream sauce and gold leaf garnish',
    });
  }
});

// Vite Middleware integration
async function startServer() {
  const isProd = process.env.NODE_ENV === 'production';

  if (!isProd) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`FoodHub Server is live on http://0.0.0.0:${PORT}`);
  });
}

startServer();
